export function getTour(slug: string) {
  return tours.find((t) => t.slug === slug);
}

export function toursByCategory(cat?: string | null) {
  if (!cat) return tours;
  return tours.filter((t) => t.category === cat);
}

export function featuredTours() {
  return tours.filter((t) => t.featured);
}

export function relatedTours(slug: string, limit = 3) {
  const current = getTour(slug);
  if (!current) return tours.slice(0, limit);
  return tours
    .filter((t) => t.slug !== slug && t.category === current.category)
    .slice(0, limit);
}
